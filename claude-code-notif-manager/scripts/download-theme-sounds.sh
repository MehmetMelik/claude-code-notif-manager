#!/bin/bash
# Downloads sounds for a specific theme preset from themes.json.
# Requires: jq (brew install jq), ffmpeg (brew install ffmpeg)
#
# Usage:
#   ./scripts/download-theme-sounds.sh sc2/protoss   # download a theme
#   ./scripts/download-theme-sounds.sh --list         # list available themes

set -eo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
THEMES_FILE="$SCRIPT_DIR/../themes/themes.json"
SOUNDS_DIR="${CLAUDE_SOUNDS_DIR:-$HOME/.claude/sounds}"
THEME_FILE="$SOUNDS_DIR/.theme"
EVENTS="start userpromptsubmit done precompact permission question"

# --- helpers ---

usage() {
  echo "Usage: $(basename "$0") <theme> | --list"
  echo ""
  echo "Download a themed sound set for Claude Code notifications."
  echo ""
  echo "Options:"
  echo "  --list    List all available themes"
  echo "  <theme>   Theme to download (e.g. sc2/protoss, wc2/horde, aoe3/british)"
  echo ""
  echo "Examples:"
  echo "  $(basename "$0") sc2/protoss"
  echo "  $(basename "$0") wc2/horde"
  echo "  $(basename "$0") aoe3/spanish"
}

check_deps() {
  local missing=0
  if ! command -v jq &>/dev/null; then
    echo "Error: jq is required. Install with: brew install jq" >&2
    missing=1
  fi
  if ! command -v ffmpeg &>/dev/null; then
    echo "Error: ffmpeg is required. Install with: brew install ffmpeg" >&2
    missing=1
  fi
  if [ ! -f "$THEMES_FILE" ]; then
    echo "Error: themes.json not found at $THEMES_FILE" >&2
    missing=1
  fi
  [ "$missing" -eq 0 ] || exit 1
}

list_themes() {
  check_deps
  echo "Available themes:"
  echo ""
  jq -r 'to_entries[] | "  \(.key)  (\(.value.game) - \(.value.faction))"' "$THEMES_FILE"
  echo ""
  echo "Usage: $(basename "$0") <theme>"
}

download_sound() {
  local event="$1" filename="$2" url="$3" label="$4"
  local dir="$SOUNDS_DIR/$event"
  local output="$dir/$filename"

  mkdir -p "$dir"

  if [ -f "$output" ]; then
    echo "  [skip] $event/$filename - $label (already exists)"
    return 0
  fi

  echo "  [download] $event/$filename - $label"
  local tmp
  tmp=$(mktemp /tmp/theme_sound_XXXXXX)

  if curl -sL -o "$tmp" "$url" && [ -s "$tmp" ]; then
    ffmpeg -y -i "$tmp" -ab 192k -loglevel error "$output"
    rm -f "$tmp"
    echo "  [ok] $event/$filename"
  else
    echo "  [error] Failed to download $event/$filename" >&2
    rm -f "$tmp"
    return 1
  fi
}

write_theme_file() {
  local theme="$1"
  echo "# Auto-generated by download-theme-sounds.sh — do not edit" > "$THEME_FILE"
  echo "# Theme: $theme" >> "$THEME_FILE"
  echo "CLAUDE_SOUND_THEME_NAME=\"$theme\"" >> "$THEME_FILE"

  for event in $EVENTS; do
    local filename
    filename=$(jq -r --arg t "$theme" --arg e "$event" '.[$t].sounds[$e].filename' "$THEMES_FILE")
    local var_name
    case "$event" in
      start)            var_name="CLAUDE_START_SOUND" ;;
      userpromptsubmit) var_name="CLAUDE_PROMPT_SOUND" ;;
      done)             var_name="CLAUDE_DONE_SOUND" ;;
      precompact)       var_name="CLAUDE_PRECOMPACT_SOUND" ;;
      permission)       var_name="CLAUDE_PERMISSION_SOUND" ;;
      question)         var_name="CLAUDE_QUESTION_SOUND" ;;
    esac
    echo "export $var_name=\"$SOUNDS_DIR/$event/$filename\"" >> "$THEME_FILE"
  done

  echo ""
  echo "Theme file written to $THEME_FILE"
}

# --- main ---

if [ $# -eq 0 ]; then
  usage
  exit 1
fi

case "$1" in
  --list|-l)
    list_themes
    exit 0
    ;;
  --help|-h)
    usage
    exit 0
    ;;
esac

THEME="$1"
check_deps

# Validate theme exists
if ! jq -e --arg t "$THEME" '.[$t]' "$THEMES_FILE" >/dev/null 2>&1; then
  echo "Error: unknown theme '$THEME'" >&2
  echo "" >&2
  echo "Available themes:" >&2
  jq -r 'keys[]' "$THEMES_FILE" >&2
  exit 1
fi

GAME=$(jq -r --arg t "$THEME" '.[$t].game' "$THEMES_FILE")
FACTION=$(jq -r --arg t "$THEME" '.[$t].faction' "$THEMES_FILE")

echo "Downloading $GAME - $FACTION sounds to $SOUNDS_DIR..."
echo ""

for event in $EVENTS; do
  filename=$(jq -r --arg t "$THEME" --arg e "$event" '.[$t].sounds[$e].filename' "$THEMES_FILE")
  url=$(jq -r --arg t "$THEME" --arg e "$event" '.[$t].sounds[$e].url' "$THEMES_FILE")
  label=$(jq -r --arg t "$THEME" --arg e "$event" '.[$t].sounds[$e].label' "$THEMES_FILE")
  download_sound "$event" "$filename" "$url" "$label"
done

write_theme_file "$THEME"

echo ""
echo "Done! Theme '$THEME' ($GAME - $FACTION) is ready."
echo "Restart your shell or run: source claude-sounds.zsh"
